    public static string Get(string key)
    {
        var culture = CultureInfo.CurrentUICulture.Name;
        var lang = culture switch
        {
            "tg" or "tj" => "tj",
            "uz" => "uz",
            "en" => "en",
            _ => "ru"
        };

        if (Text.TryGetValue(lang, out var values) && values.TryGetValue(key, out var value))
        {
            return value;
        }

        return key;
    }
